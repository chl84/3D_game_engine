#!/usr/bin/env python3
"""Generate docs/API_REFERENCE.md from engine schema output."""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

import jsonschema

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "API_REFERENCE.md"

CLI_COMMANDS = [
    ("engine --version --json", "Build and version metadata"),
    ("engine doctor --json", "OS, compiler, Vulkan, devices and checks"),
    ("engine schema --json", "Component and command schemas"),
    ("engine project create|validate|unlock --json", "Project lifecycle"),
    ("engine scene create|inspect|validate --json", "Scene lifecycle"),
    ("engine entity create|delete|reparent --json", "Entity lifecycle"),
    ("engine component set|add|remove --json", "Component changes"),
    ("engine simulate --ticks N --json", "Fixed-tick state dump"),
    ("engine batch --file FILE --undo N --json", "Transactional command batch"),
    ("engine screenshot <project> <scene> --frames N --out FILE --json", "Offscreen PNG screenshot"),
    ("engine run <project> <scene> [--frames N] [--json]", "Windowed fly-camera demo"),
]


def fail(message: str) -> int:
    print(f"error: {message}", file=sys.stderr)
    return 1


def schema_document(engine: str) -> dict[str, Any]:
    result = subprocess.run(
        [engine, "schema", "--json"], check=False, capture_output=True, text=True
    )
    if result.returncode != 0:
        raise RuntimeError(f"engine schema exited with {result.returncode}: {result.stderr.strip()}")
    document = json.loads(result.stdout)
    envelope = json.loads(
        (ROOT / "schemas" / "command-result@1.schema.json").read_text(encoding="utf-8")
    )
    jsonschema.Draft7Validator(envelope).validate(document)
    if document.get("status") != "ok":
        raise RuntimeError("engine schema did not report status ok")
    return document["data"]


def type_label(property_schema: dict[str, Any]) -> str:
    value_type = property_schema.get("type", "unknown")
    if isinstance(value_type, list):
        value_type = " or ".join(value_type)
    if value_type == "array":
        items = property_schema.get("items", {}).get("type", "unknown")
        count = property_schema.get("minItems")
        return f"array[{items}]" + (f"[{count}]" if count is not None else "")
    return str(value_type)


def generate(data: dict[str, Any]) -> str:
    components = data.get("components", {})
    commands = data.get("commands", {})
    if not isinstance(components, dict) or not isinstance(commands, dict):
        raise RuntimeError("schema data is missing components or commands")

    lines: list[str] = [
        "# API Reference",
        "",
        "**Status:** Generated from the command registry and reflection metadata by",
        "`scripts/generate_api_reference.py`. Do not edit this file by hand.",
        "",
        "## CLI surface",
        "",
        "| Command | Purpose |",
        "|---|---|",
    ]
    for command, purpose in CLI_COMMANDS:
        lines.append(f"| `{command}` | {purpose} |")

    lines += [
        "",
        "All offline commands return a document that validates against",
        "`schemas/command-result@1.schema.json`.",
        "",
        "## Components",
        "",
        "| Component | Fields |",
        "|---|---|",
    ]
    for name in sorted(components):
        schema = components[name]
        properties = schema.get("properties", {})
        fields = ", ".join(
            f"`{field}`: {type_label(property_schema)}"
            for field, property_schema in sorted(properties.items())
        )
        lines.append(f"| `{name}` | {fields} |")

    lines += ["", "## Commands", ""]
    for name in sorted(commands):
        schema = commands[name]
        required = schema.get("required", [])
        required_text = ", ".join(f"`{field}`" for field in required) if required else "none"
        lines += [
            f"### `{name}`",
            "",
            f"Required arguments: {required_text}",
            "",
            "```json",
            json.dumps(schema, indent=2, sort_keys=True),
            "```",
            "",
        ]

    lines += [
        "## Error contract",
        "",
        "| Error code | Exit code | Meaning |",
        "|---|---|---|",
        "| `E_USAGE` | 2 | Usage error, unknown command or invalid argument |",
        "| `E_VALIDATION` | 3 | Validation error |",
        "| `E_NOT_FOUND` | 4 | Not found |",
        "| `E_CONFLICT` | 5 | Conflict or locked resource |",
        "| `E_IO` | 6 | I/O or filesystem error |",
        "| `E_UNSUPPORTED` | 7 | Unsupported format or version |",
        "| `E_PRECONDITION` | 8 | A required capability is missing |",
        "| `E_INTERNAL` | 1 | Internal error |",
        "| `E_CANCELLED` | 130 | Cancelled by the user |",
        "",
        "The codes and exit codes are stable and are part of the public contract.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--engine", required=True, help="Path to the engine binary.")
    parser.add_argument("--check", action="store_true", help="Check instead of writing.")
    arguments = parser.parse_args()

    try:
        content = generate(schema_document(arguments.engine))
    except (RuntimeError, OSError, json.JSONDecodeError, jsonschema.ValidationError) as error:
        return fail(str(error))

    if arguments.check:
        current = OUTPUT.read_text(encoding="utf-8")
        if current != content:
            return fail("docs/API_REFERENCE.md is out of date; run the generator")
        print("API reference is up to date")
        return 0

    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
